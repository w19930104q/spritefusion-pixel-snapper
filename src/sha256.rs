//! Deterministic SHA-256 implementation (FIPS 180-4), dependency-free.
//!
//! Only what the pipeline needs to hash output PNG bytes: one-shot hashing
//! and lowercase hex formatting. Implemented locally so the crate's dependency
//! set stays unchanged and results are reproducible across toolchains.

